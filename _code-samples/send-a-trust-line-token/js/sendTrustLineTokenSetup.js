// Setup script for the Send a Trust Line Token tutorial
import xrpl from 'xrpl'
import fs from 'fs'
import { fileURLToPath } from 'url'

// TST is a test token on Testnet. Its issuer has
// Default Ripple enabled and keeps standing DEX offers at ~1 TST = 10 XRP
// (plus spread), so anyone can buy it with faucet XRP.
const TST_ISSUER = 'rP9jPyP5kyvFRb6ZiRghAGw5u8SGAmU4bd'
const CURRENCY_CODE = 'TST'
const TOTAL_STEPS = 3

export async function setup() {
  process.stdout.write(`Setting up tutorial: 0/${TOTAL_STEPS}\r`)

  const client = new xrpl.Client('wss://s.altnet.rippletest.net:51233')
  await client.connect()

  // Fund the sender wallet from the Testnet faucet
  const { wallet: sender } = await client.fundWallet()

  process.stdout.write(`Setting up tutorial: 1/${TOTAL_STEPS}\r`)

  // Create a trust line from the sender to the TST issuer so the sender can hold TST
  const trustSetResponse = await client.submitAndWait({
    TransactionType: 'TrustSet',
    Account: sender.address,
    LimitAmount: {
      currency: CURRENCY_CODE,
      issuer: TST_ISSUER,
      value: '1000000000'
    }
  }, { wallet: sender, autofill: true })

  if (trustSetResponse.result.meta?.TransactionResult !== 'tesSUCCESS') {
    await client.disconnect()
    throw new Error(`Sender TrustSet failed: ${trustSetResponse.result.meta?.TransactionResult}`)
  }

  process.stdout.write(`Setting up tutorial: 2/${TOTAL_STEPS}\r`)

  // Buy TST on the DEX so the sender has a balance to send. The sender offers
  // up to 60 XRP for 5 TST (12 XRP each), which crosses the issuer's standing
  // sell offer at ~11.5 XRP per TST. tfFillOrKill ensures the whole amount is
  // bought or the transaction fails, so nothing is left on the order book.
  const offerCreateResponse = await client.submitAndWait({
    TransactionType: 'OfferCreate',
    Account: sender.address,
    TakerPays: {
      currency: CURRENCY_CODE,
      issuer: TST_ISSUER,
      value: '5'
    },
    TakerGets: xrpl.xrpToDrops('60'),
    Flags: xrpl.OfferCreateFlags.tfFillOrKill
  }, { wallet: sender, autofill: true })

  if (offerCreateResponse.result.meta?.TransactionResult !== 'tesSUCCESS') {
    await client.disconnect()
    throw new Error(`Sender OfferCreate failed: ${offerCreateResponse.result.meta?.TransactionResult}`)
  }

  process.stdout.write(`Setting up tutorial: 3/${TOTAL_STEPS}\r`)

  // Write setup data
  const setupData = {
    description: 'This file is auto-generated by sendTrustLineTokenSetup.js. It stores XRPL account info for use in the Send a Trust Line Token tutorial.',
    sender: {
      address: sender.address,
      seed: sender.seed
    }
  }

  fs.writeFileSync('sendTrustLineTokenSetup.json', JSON.stringify(setupData, null, 2))

  process.stdout.write('Setting up tutorial: Complete!\n')

  await client.disconnect()
}

// Allow running this file directly: `node sendTrustLineTokenSetup.js`
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await setup()
}
