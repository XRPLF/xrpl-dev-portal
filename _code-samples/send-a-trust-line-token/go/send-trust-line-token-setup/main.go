// Setup script for the Send a Trust Line Token tutorial
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"time"

	"github.com/Peersyst/xrpl-go/pkg/crypto"
	"github.com/Peersyst/xrpl-go/xrpl/faucet"
	"github.com/Peersyst/xrpl-go/xrpl/queries/account"
	"github.com/Peersyst/xrpl-go/xrpl/queries/common"
	"github.com/Peersyst/xrpl-go/xrpl/rpc"
	rpctypes "github.com/Peersyst/xrpl-go/xrpl/rpc/types"
	"github.com/Peersyst/xrpl-go/xrpl/transaction"
	"github.com/Peersyst/xrpl-go/xrpl/transaction/types"
	"github.com/Peersyst/xrpl-go/xrpl/wallet"
)

// TST is a test token on Testnet. Its issuer has
// Default Ripple enabled and keeps standing DEX offers at ~1 TST = 10 XRP
// (plus spread), so anyone can buy it with faucet XRP.
const (
	tstIssuer    = "rP9jPyP5kyvFRb6ZiRghAGw5u8SGAmU4bd"
	currencyCode = "TST"
	totalSteps   = 3
)

func main() {
	cfg, err := rpc.NewClientConfig(
		"https://s.altnet.rippletest.net:51234",
		rpc.WithFaucetProvider(faucet.NewTestnetFaucetProvider()),
	)
	if err != nil {
		panic(err)
	}
	client := rpc.NewClient(cfg)

	submitOpts := func(w *wallet.Wallet) *rpctypes.SubmitOptions {
		return &rpctypes.SubmitOptions{Autofill: true, Wallet: w}
	}

	fmt.Printf("Setting up tutorial: 0/%d\r", totalSteps)

	// Fund the sender wallet
	ch := make(chan wallet.Wallet, 1)
	createAndFund := func() {
		w, err := wallet.New(crypto.ED25519())
		if err != nil {
			panic(err)
		}
		if err := client.FundWallet(&w); err != nil {
			panic(err)
		}
		// Poll until account is validated on ledger
		funded := false
		for range 20 {
			_, err := client.Request(&account.InfoRequest{
				Account:     w.GetAddress(),
				LedgerIndex: common.Validated,
			})
			if err == nil {
				funded = true
				break
			}
			time.Sleep(time.Second)
		}
		if !funded {
			panic("Issue funding account: " + w.GetAddress().String())
		}
		ch <- w
	}
	go createAndFund()
	sender := <-ch

	fmt.Printf("Setting up tutorial: 1/%d\r", totalSteps)

	// Create a trust line from the sender to the TST issuer so the sender can hold TST
	trustSetTx := transaction.TrustSet{
		BaseTx: transaction.BaseTx{Account: sender.ClassicAddress},
		LimitAmount: types.IssuedCurrencyAmount{
			Currency: currencyCode,
			Issuer:   tstIssuer,
			Value:    "1000000000",
		},
	}
	trustSetResp, err := client.SubmitTxAndWait(trustSetTx.Flatten(), submitOpts(&sender))
	if err != nil {
		panic(err)
	}
	if trustSetResp.Meta.TransactionResult != "tesSUCCESS" {
		panic("Sender TrustSet failed: " + trustSetResp.Meta.TransactionResult)
	}

	fmt.Printf("Setting up tutorial: 2/%d\r", totalSteps)

	// Buy TST on the DEX so the sender has a balance to send. The sender offers
	// up to 60 XRP for 5 TST (12 XRP each), which crosses the issuer's standing
	// sell offer at ~11.5 XRP per TST. tfFillOrKill ensures the whole amount is
	// bought or the transaction fails, so nothing is left on the order book.
	offerCreateTx := transaction.OfferCreate{
		BaseTx: transaction.BaseTx{Account: sender.ClassicAddress},
		TakerPays: types.IssuedCurrencyAmount{
			Currency: currencyCode,
			Issuer:   tstIssuer,
			Value:    "5",
		},
		TakerGets: types.XRPCurrencyAmount(60000000), // 60 XRP in drops
	}
	offerCreateTx.SetFillOrKillFlag()
	offerCreateResp, err := client.SubmitTxAndWait(offerCreateTx.Flatten(), submitOpts(&sender))
	if err != nil {
		panic(err)
	}
	if offerCreateResp.Meta.TransactionResult != "tesSUCCESS" {
		panic("Sender OfferCreate failed: " + offerCreateResp.Meta.TransactionResult)
	}

	fmt.Printf("Setting up tutorial: 3/%d\r", totalSteps)

	// Write setup data
	setupData := struct {
		Description string `json:"description"`
		Sender      any    `json:"sender"`
	}{
		Description: "This file is auto-generated by go/send-trust-line-token-setup/main.go. It stores XRPL account info for use in the Send a Trust Line Token tutorial.",
		Sender: map[string]string{
			"address": sender.ClassicAddress.String(),
			"seed":    sender.Seed,
		},
	}

	jsonData, err := json.MarshalIndent(setupData, "", "  ")
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("send-trust-line-token-setup.json", jsonData, 0644); err != nil {
		panic(err)
	}

	fmt.Println("Setting up tutorial: Complete!")
}
